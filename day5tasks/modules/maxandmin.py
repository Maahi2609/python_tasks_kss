import math
num = [4, 12, 54, 90, 122, 145, 178, 199, 200]
maximum_value = max(num)
minimum_value = min(num)
print("maximum value : ", maximum_value)
print("minimum value : ", minimum_value)
print("square root of maximum value : ", math.sqrt(maximum_value))
print("logarithm of minimum value : ", math.log(minimum_value))